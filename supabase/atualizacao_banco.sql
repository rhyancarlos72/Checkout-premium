-- ===== 20261104000000_expired_stay_pending.sql =====
-- Pix vencido continua em "vendas pendentes": volta para pendente os pedidos marcados como expirados.
-- (Novos Pix vencidos já não mudam de status; o envio de sale.canceled fica registrado em events.type = 'pix_expired'.)
insert into public.events (order_id, checkout_id, type, data)
select o.id, o.checkout_id, 'pix_expired', '{}'::jsonb
from public.orders o
where o.status = 'expired'
  and not exists (select 1 from public.events e where e.order_id = o.id and e.type = 'pix_expired');

update public.orders set status = 'pending' where status = 'expired';

create index if not exists events_order_type_idx on public.events(order_id, type);

-- ===== 20261105000000_admin_roles.sql =====
-- Equipe com papéis: "owner" (dono, acesso total) e "staff" (equipe, sem integrações).
-- O admin que já existe vira dono. Credenciais (tabela settings) ficam acessíveis só ao dono,
-- e só o dono pode adicionar/remover pessoas (evita que alguém da equipe se promova).
alter table public.admins add column if not exists role text not null default 'owner';
alter table public.admins add column if not exists email text;
do $$ begin
  alter table public.admins add constraint admins_role_check check (role in ('owner','staff'));
exception when duplicate_object then null; end $$;
update public.admins a set email = u.email from auth.users u where u.id = a.user_id and a.email is null;

create or replace function public.is_owner()
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid() and role = 'owner');
$$;

-- admins: cada um lê a própria linha; só o dono gerencia
drop policy if exists admin_all on public.admins;
drop policy if exists admins_read on public.admins;
drop policy if exists admins_owner_write on public.admins;
create policy admins_read on public.admins for select to authenticated using (user_id = auth.uid() or public.is_owner());
create policy admins_owner_write on public.admins for all to authenticated using (public.is_owner()) with check (public.is_owner());

-- credenciais (Woovi, Efí, Evolution, webhooks) e logs de integração: só o dono
do $$ declare t text; begin
  foreach t in array array['settings','integration_logs','webhook_logs'] loop
    execute format('drop policy if exists admin_all on public.%I', t);
    execute format('drop policy if exists owner_all on public.%I', t);
    execute format('create policy owner_all on public.%I for all to authenticated using (public.is_owner()) with check (public.is_owner())', t);
  end loop;
end $$;

-- ===== 20261106000000_invoices.sql =====
-- Notas fiscais (Spedy): UMA nota por pedido (order_id único), somando produto + order bumps.
create table if not exists public.invoices (
  id           uuid primary key default gen_random_uuid(),
  order_id     uuid not null unique references public.orders(id) on delete cascade,
  type         text not null check (type in ('service','product')),
  status       text not null default 'processing' check (status in ('processing','issued','error','canceled')),
  provider_id  text,               -- id da nota na Spedy
  amount_cents integer not null,
  number       text,
  message      text,               -- motivo de erro / detalhe da prefeitura/SEFAZ
  response     jsonb not null default '{}'::jsonb,
  attempts     integer not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists invoices_status_idx on public.invoices(status, updated_at);

alter table public.invoices enable row level security;
drop policy if exists admin_all on public.invoices;
create policy admin_all on public.invoices for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ===== 20261107000000_upsells.sql =====
-- Upsell pós-compra: 1 oferta por produto principal, exibida em popup quando o Pix é aprovado.
-- Aceitou → novo pedido só do produto oferecido (Pix próprio), ligado ao pedido original.
create table if not exists public.upsells (
  id               uuid primary key default gen_random_uuid(),
  product_id       uuid not null unique references public.products(id) on delete cascade, -- produto principal
  offer_product_id uuid not null references public.products(id) on delete cascade,        -- produto oferecido
  headline         text,
  title            text,
  description      text,
  image_url        text,
  price_cents      integer not null check (price_cents >= 1),
  compare_at_cents integer,
  cta_text         text,
  active           boolean not null default true,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
alter table public.upsells enable row level security;
drop policy if exists admin_all on public.upsells;
create policy admin_all on public.upsells for all to authenticated using (public.is_admin()) with check (public.is_admin());
create index if not exists orders_upsell_of_idx on public.orders ((tracking->>'upsell_of'));

-- ===== 20261108000000_access_requests.sql =====
-- Pedidos de cadastro feitos na tela de login ("Criar cadastro").
-- Ninguém entra sozinho: o dono aprova em Configurações → Equipe e só então a pessoa recebe o link de senha.
create table if not exists public.access_requests (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  email      text not null,
  phone      text,
  company    text,
  message    text,
  status     text not null default 'pending' check (status in ('pending','approved','rejected')),
  ip         text,
  created_at timestamptz not null default now(),
  decided_at timestamptz
);
create unique index if not exists access_requests_pending_email_uq on public.access_requests (lower(email)) where status = 'pending';
alter table public.access_requests enable row level security;
drop policy if exists owner_all on public.access_requests;
create policy owner_all on public.access_requests for all to authenticated using (public.is_owner()) with check (public.is_owner());

